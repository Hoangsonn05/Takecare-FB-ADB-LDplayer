from __future__ import annotations

from enum import Enum


class FailureCode(str, Enum):
    AUTH_INVALID = "AUTH_INVALID"
    ACCOUNT_NOT_SELECTED = "ACCOUNT_NOT_SELECTED"
    DEVICE_NOT_SELECTED = "DEVICE_NOT_SELECTED"
    ACCOUNT_DEVICE_BINDING_MISSING = "ACCOUNT_DEVICE_BINDING_MISSING"
    ADB_OFFLINE = "ADB_OFFLINE"
    FACEBOOK_NOT_INSTALLED = "FACEBOOK_NOT_INSTALLED"
    FACEBOOK_NOT_FOREGROUND = "FACEBOOK_NOT_FOREGROUND"
    JOB_EMPTY = "JOB_EMPTY"
    JOB_INVALID = "JOB_INVALID"
    JOB_LINK_MISSING = "JOB_LINK_MISSING"
    JOB_LINK_INVALID = "JOB_LINK_INVALID"
    JOB_TARGET_INVALID = "JOB_TARGET_INVALID"
    JOB_LINK_REDIRECT_INVALID = "JOB_LINK_REDIRECT_INVALID"
    UNSUPPORTED_JOB_ACTION = "UNSUPPORTED_JOB_ACTION"
    UNSUPPORTED_CONTENT_TYPE = "UNSUPPORTED_CONTENT_TYPE"
    LINK_NOT_OPENED = "LINK_NOT_OPENED"
    FACEBOOK_VIEW_HANDLER_NOT_FOUND = "FACEBOOK_VIEW_HANDLER_NOT_FOUND"
    FACEBOOK_ROUTE_COMMAND_FAILED = "FACEBOOK_ROUTE_COMMAND_FAILED"
    FACEBOOK_ROUTE_COMPONENT_REJECTED = "FACEBOOK_ROUTE_COMPONENT_REJECTED"
    FACEBOOK_ROUTE_RETURNED_HOME = "FACEBOOK_ROUTE_RETURNED_HOME"
    FACEBOOK_ROUTE_TIMEOUT = "FACEBOOK_ROUTE_TIMEOUT"
    TARGET_NOT_VERIFIED = "TARGET_NOT_VERIFIED"
    TARGET_LAYOUT_MISMATCH = "TARGET_LAYOUT_MISMATCH"
    LIKE_BUTTON_NOT_FOUND_AFTER_SCROLL = "LIKE_BUTTON_NOT_FOUND_AFTER_SCROLL"
    REEL_LIKE_BUTTON_NOT_FOUND = "REEL_LIKE_BUTTON_NOT_FOUND"
    REACTION_PANEL_NOT_OPENED = "REACTION_PANEL_NOT_OPENED"
    REACTION_TARGET_NOT_FOUND = "REACTION_TARGET_NOT_FOUND"
    ACTION_COMMAND_FAILED = "ACTION_COMMAND_FAILED"
    ACTION_NOT_CONFIRMED = "ACTION_NOT_CONFIRMED"
    REACTION_TYPE_MISMATCH = "REACTION_TYPE_MISMATCH"
    ACTION_RESULT_UNKNOWN = "ACTION_RESULT_UNKNOWN"
    API_GET_FAILED = "API_GET_FAILED"
    API_SUBMIT_FAILED = "API_SUBMIT_FAILED"
    API_REPORT_FAILED = "API_REPORT_FAILED"
    STOP_REQUESTED = "STOP_REQUESTED"


JOB_FAILURES = frozenset(
    {
        FailureCode.JOB_INVALID,
        FailureCode.JOB_LINK_MISSING,
        FailureCode.JOB_LINK_INVALID,
        FailureCode.JOB_TARGET_INVALID,
        FailureCode.JOB_LINK_REDIRECT_INVALID,
        FailureCode.UNSUPPORTED_JOB_ACTION,
        FailureCode.UNSUPPORTED_CONTENT_TYPE,
        FailureCode.LINK_NOT_OPENED,
        FailureCode.FACEBOOK_ROUTE_RETURNED_HOME,
        FailureCode.FACEBOOK_ROUTE_TIMEOUT,
        FailureCode.TARGET_NOT_VERIFIED,
        FailureCode.TARGET_LAYOUT_MISMATCH,
        FailureCode.LIKE_BUTTON_NOT_FOUND_AFTER_SCROLL,
        FailureCode.REEL_LIKE_BUTTON_NOT_FOUND,
        FailureCode.REACTION_PANEL_NOT_OPENED,
        FailureCode.REACTION_TARGET_NOT_FOUND,
        FailureCode.ACTION_COMMAND_FAILED,
        FailureCode.ACTION_NOT_CONFIRMED,
        FailureCode.REACTION_TYPE_MISMATCH,
        FailureCode.ACTION_RESULT_UNKNOWN,
    }
)


def should_report_failure(
    code: FailureCode,
    *,
    report_unsupported_actions: bool = False,
) -> bool:
    if code is FailureCode.UNSUPPORTED_JOB_ACTION:
        return report_unsupported_actions
    return code in JOB_FAILURES
